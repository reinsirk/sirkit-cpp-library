// KnapsackByValue(items): 価値を添字に最小重量を前計算する。n品、総価値VでO((n+1)(V+1))時間・O(V+1)領域。
// minimum_weight(value): 価値がちょうどvalueとなる最小重量。到達不能またはuint64_t外ならnullopt。O(1)。
// max_value(budget): 重量がbudget以下で選べる最大価値。O(log(V+2))。
