#include "Verify/current/common/fast_io.hpp"

#include <utility>
#include <vector>

int main()
{
    int n{}, m{};
    verify_in >> n >> m;
    std::vector<std::pair<int, int>> edges(m);
    for (auto &[u, v] : edges)
    {
        verify_in >> u >> v;
        --u;
        --v;
    }
    for (const int distance : sirkit::edge_removal_distances(n, edges, 0, n - 1))
    {
        verify_out << distance << '\n';
    }
}
